interface PropertySchema {
  readonly type?: unknown;
  readonly properties?: Readonly<Record<string, PropertySchema>>;
  readonly required?: readonly string[];
  readonly additionalProperties?: unknown;
  readonly items?: PropertySchema;
  readonly anyOf?: readonly PropertySchema[];
  readonly $ref?: string;
  readonly enum?: readonly unknown[];
  readonly const?: unknown;
  readonly pattern?: string;
}

/** The type of one member, as written into shapes.ts. */
type Member =
  | { readonly type: 'string' | 'digest' | 'integer' | 'number' | 'boolean' | 'raw' | 'object' }
  | { readonly type: 'enum' | 'shape'; readonly name: string }
  | { readonly type: 'array'; readonly items: Member }
  | { readonly type: 'map'; readonly values: Member }
  | { readonly type: 'nullable'; readonly of: Member };

interface Field {
  readonly name: string;
  readonly optional: boolean;
  readonly member: Member;
  readonly ts: string;
}

interface Shape {
  readonly name: string;
  readonly doc: string;
  readonly required: readonly string[];
  readonly optional: readonly string[];
  readonly fields: Field[];
}

interface Enum {
  readonly name: string;
  readonly values: readonly string[];
}

interface Tables {
  readonly shapes: readonly Shape[];
  readonly enums: readonly Enum[];
}

class Generator {
  readonly shapes: Shape[] = [];
  readonly enums = new Map<string, readonly string[]>();
  readonly usedInline = new Set<string>();
  readonly usedEnum = new Set<string>();

  shape(name: string, doc: string, def: PropertySchema): void {
    if (def.type !== 'object' || def.properties === undefined) {
      throw new Error(`${name} is not an object definition with properties`);
    }
    if (def.additionalProperties !== false) {
      throw new Error(`${name}: additionalProperties is not false`);
    }
    const members = Object.keys(def.properties);
    const required = def.required ?? [];
    for (const r of required) {
      if (!members.includes(r)) throw new Error(`${name}: required member ${r} has no property`);
    }
    const shape: Shape = {
      name,
      doc,
      required: members.filter((m) => required.includes(m)),
      optional: members.filter((m) => !required.includes(m)),
      fields: [],
    };
    this.shapes.push(shape);
    // The owner comes first; an inline shape is pushed while its member is read.
    for (const [m, prop] of Object.entries(def.properties)) {
      const [member, ts] = this.member(`${name}.${m}`, name, m, prop);
      shape.fields.push({ name: m, optional: !required.includes(m), member, ts });
    }
  }

  member(key: string, owner: string, m: string, p: PropertySchema): [Member, string] {
    // An anyOf beside a type only constrains values of that type (the
    // URI-or-token items of GatewayMetadata.extensions_supported); the type
    // decides the member.
    if (p.anyOf !== undefined && p.type === undefined) {
      const [first, second] = p.anyOf;
      if (
        p.anyOf.length === 2 &&
        first !== undefined &&
        JSON.stringify(second) === '{"type":"null"}'
      ) {
        const [of, ts] = this.member(key, owner, m, first);
        return [{ type: 'nullable', of }, `${ts} | null`];
      }
      return [{ type: 'raw' }, 'RawJSON'];
    }
    if (p.$ref !== undefined) {
      const name = p.$ref.replace(/^#\/\$defs\//, '');
      return [{ type: 'shape', name }, name];
    }
    if (p.enum !== undefined) {
      const name = ENUM_MEMBERS[key];
      if (name === undefined) throw new Error(`${key}: schema enum has no enum name`);
      if (ENUMS[name] === undefined) throw new Error(`${key}: enum ${name} is not declared`);
      const values = p.enum.map((v) => {
        if (typeof v !== 'string')
          throw new Error(`${key}: enum value ${String(v)} is not a string`);
        return v;
      });
      const prev = this.enums.get(name);
      if (prev !== undefined && JSON.stringify(prev) !== JSON.stringify(values)) {
        throw new Error(`${key}: enum ${name} has two different value lists`);
      }
      this.enums.set(name, values);
      this.usedEnum.add(key);
      return [{ type: 'enum', name }, name];
    }
    if (p.const !== undefined) {
      if (typeof p.const === 'string') return [{ type: 'string' }, 'string'];
      if (Number.isInteger(p.const)) return [{ type: 'integer' }, 'number'];
      throw new Error(`${key}: unhandled const ${JSON.stringify(p.const)}`);
    }
    switch (p.type) {
      case undefined:
        return [{ type: 'raw' }, 'RawJSON'];
      case 'string':
        return p.pattern === DIGEST_PATTERN
          ? [{ type: 'digest' }, 'Digest']
          : [{ type: 'string' }, 'string'];
      case 'integer':
        return [{ type: 'integer' }, 'number'];
      case 'number':
        return [{ type: 'number' }, 'number'];
      case 'boolean':
        return [{ type: 'boolean' }, 'boolean'];
      case 'array': {
        if (p.items === undefined) throw new Error(`${key}: array without items`);
        if (p.items.properties !== undefined) {
          throw new Error(`${key}: array of inline objects has no shape name`);
        }
        const [items, ts] = this.member(key, owner, m, p.items);
        return [{ type: 'array', items }, `readonly ${ts.includes(' ') ? `(${ts})` : ts}[]`];
      }
      case 'object': {
        if (p.properties !== undefined) {
          const name = NAMED_INLINE[key];
          if (name === undefined) throw new Error(`${key}: inline object has no shape name`);
          this.usedInline.add(key);
          this.shape(name, `The \`${m}\` member of {@link ${owner}}.`, p);
          return [{ type: 'shape', name }, name];
        }
        if (typeof p.additionalProperties === 'object' && p.additionalProperties !== null) {
          const [values, ts] = this.member(key, owner, m, p.additionalProperties as PropertySchema);
          return [{ type: 'map', values }, `Readonly<Record<string, ${ts}>>`];
        }
        return [{ type: 'object' }, 'PactObject'];
      }
    }
    throw new Error(`${key}: unhandled schema ${JSON.stringify(p)}`);
  }
}

export function tables(schema: {
  readonly $defs?: Readonly<Record<string, PropertySchema>>;
}): Tables {
  const defs = schema.$defs;
  if (defs === undefined) throw new Error('the schema has no $defs');
  const g = new Generator();
  for (const name of PAYLOAD_ONLY) {
    if (defs[name] === undefined) throw new Error(`payload-only ${name} is not in the schema`);
  }
  for (const [name, def] of Object.entries(defs)) {
    if (PAYLOAD_ONLY.includes(name)) continue;
    g.shape(name, `The \`${name}\` object of the schema (\`$defs/${name}\`).`, def);
  }
  for (const key of Object.keys(NAMED_INLINE)) {
    if (!g.usedInline.has(key)) throw new Error(`${key}: named inline object is not in the schema`);
  }
  for (const key of Object.keys(ENUM_MEMBERS)) {
    if (!g.usedEnum.has(key)) throw new Error(`${key}: enum member is not in the schema`);
  }
  const enums: Enum[] = [];
  for (const name of Object.keys(ENUMS)) {
    const values = g.enums.get(name);
    if (values === undefined) throw new Error(`enum ${name} is not used by the schema`);
    enums.push({ name, values });
  }
  return { shapes: g.shapes, enums };
}

function list(names: readonly string[]): string {
  if (names.length === 0) return '[]';
  return `[\n${names.map((n) => `      '${n}',\n`).join('')}    ]`;
}

function literal(m: Member): string {
  switch (m.type) {
    case 'enum':
    case 'shape':
      return `{ type: '${m.type}', name: '${m.name}' }`;
    case 'array':
      return `{ type: 'array', items: ${literal(m.items)} }`;
    case 'map':
      return `{ type: 'map', values: ${literal(m.values)} }`;
    case 'nullable':
      return `{ type: 'nullable', of: ${literal(m.of)} }`;
    default:
      return `{ type: '${m.type}' }`;
  }
}

export function renderShapes(t: Tables): string {
  const body = t.shapes
    .map(
      (s) =>
        `  ${s.name}: {\n    required: ${list(s.required)},\n    optional: ${list(s.optional)},\n` +
        `    members: {\n${s.fields.map((f) => `      ${f.name}: ${literal(f.member)},\n`).join('')}    },\n  },\n`,
    )
    .join('');
  return `${HEADER}
/**
 * The type of one member, as the strict decoder checks it (Go: the field type
 * of the struct):
 *
 * - \`string\`, \`digest\` (a \`Digest\` string), \`enum\` (a string of the
 *   named enum of enums.ts; the decoder does not check the value);
 * - \`integer\` (0..2^53-1), \`number\`, \`boolean\`;
 * - \`raw\`: any JSON value, kept as received (\`RawJSON\`);
 * - \`object\`: an open object of raw member values (\`PactObject\`);
 * - \`shape\`: an object of the named shape;
 * - \`array\` of \`items\`, \`map\` (an object) of \`values\`, and \`nullable\`:
 *   \`null\` or \`of\`.
 *
 * Every other member type rejects \`null\`.
 */
export type Member =
  | { readonly type: 'string' | 'digest' | 'integer' | 'number' | 'boolean' | 'raw' | 'object' }
  | { readonly type: 'enum' | 'shape'; readonly name: string }
  | { readonly type: 'array'; readonly items: Member }
  | { readonly type: 'map'; readonly values: Member }
  | { readonly type: 'nullable'; readonly of: Member };

/**
 * The members of an object definition, each list in the order of the schema's
 * properties, and the type of each member.
 */
export interface Shape {
  readonly required: readonly string[];
  readonly optional: readonly string[];
  readonly members: Readonly<Record<string, Member>>;
}

/** One shape per $defs entry of the schema, each inline object shape after its owner. */
export const shapes = {
${body}} as const satisfies Readonly<Record<string, Shape>>;
`;
}

export function renderTypes(t: Tables): string {
  const used = new Set<string>();
  for (const s of t.shapes) {
    for (const f of s.fields) for (const w of f.ts.match(/\w+/g) ?? []) used.add(w);
  }
  const enumImports = t.enums
    .map((e) => e.name)
    .filter((n) => used.has(n))
    .sort();
  const valueImports = ['Digest', 'PactObject', 'RawJSON'].filter((n) => used.has(n));
  const imports =
    `import type {\n${enumImports.map((n) => `  ${n},\n`).join('')}} from './enums.ts';\n` +
    `import type { ${valueImports.join(', ')} } from './values.ts';\n`;
  const body = t.shapes
    .map(
      (s) =>
        `/** ${s.doc} */\nexport interface ${s.name} {\n` +
        s.fields.map((f) => `  readonly ${f.name}${f.optional ? '?' : ''}: ${f.ts};\n`).join('') +
        '}\n',
    )
    .join('\n');
  return `${HEADER}
// One readonly interface per object definition of the schema, with the JSON
// member names and the required and optional split (Go package core).
// Decode untrusted input with core/strictjson and the matching shape of
// shapes.ts; the interfaces do not enforce the schema's patterns, lengths or
// numeric ranges.

${imports}
${body}`;
}

function memberName(value: string): string {
  return value.toUpperCase().replaceAll('-', '_');
}

export function renderEnums(t: Tables): string {
  const body = t.enums
    .map((e) => {
      const set = `${e.name.charAt(0).toLowerCase()}${e.name.slice(1)}Values`;
      return (
        `/** ${ENUMS[e.name]} */\nexport const ${e.name} = Object.freeze({\n` +
        e.values.map((v) => `  ${memberName(v)}: '${v}',\n`).join('') +
        `} as const);\n\n/** ${ENUMS[e.name]} */\nexport type ${e.name} = (typeof ${e.name})[keyof typeof ${e.name}];\n\n` +
        `const ${set}: ReadonlySet<string> = new Set(Object.values(${e.name}));\n\n` +
        `/** Reports whether \`x\` is a {@link ${e.name}} value (Go \`${e.name}.Valid\`). */\n` +
        `export function is${e.name}(x: unknown): x is ${e.name} {\n` +
        `  return typeof x === 'string' && ${set}.has(x);\n}\n`
      );
    })
    .join('\n');
  return `${HEADER}
// The string enums of the schema (Go package core): a frozen table from
// member name to value, the union of the values, and a guard.

${body}`;
}

const OUTPUTS: readonly { readonly name: string; readonly render: (t: Tables) => string }[] = [
  { name: 'src/core/types.ts', render: renderTypes },
  { name: 'src/core/enums.ts', render: renderEnums },
  { name: 'src/core/shapes.ts', render: renderShapes },
];

function main(argv: readonly string[]): number {
  const check = argv.includes('--check');
  if (argv.some((a) => a !== '--check')) {
    process.stderr.write('usage: node scripts/gen-types.ts [--check]\n');
    return 2;
  }
  const t = tables(JSON.parse(readFileSync(SCHEMA, 'utf8')));
  let status = 0;
  for (const out of OUTPUTS) {
    const path = fileURLToPath(new URL(`../${out.name}`, import.meta.url));
    const text = out.render(t);
    if (!check) {
      writeFileSync(path, text);
      continue;
    }
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // compared as empty
    }
    if (current !== text) {
      process.stderr.write(`${out.name} is stale; run pnpm run gen\n`);
      status = 1;
    }
  }
  return status;
}

process.exitCode = main(process.argv.slice(2));
