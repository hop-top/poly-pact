<?php

declare(strict_types=1);

/*
 * Generator of the wire types of namespace HopTop\Pact\Core (Go package
 * core) from the vendored schema, schema/pact.schema.json.
 *
 * Output, all under src/Core/, one file per class as PSR-4 wants:
 *
 * - one final readonly class per object definition of $defs, except the
 *   payload-only ConformanceDeclaration and TransportDeclaration, plus one per
 *   inline object member (GatewayEndpoints, ReputationDimensions, named as the
 *   Go structs). Properties are named as the JSON members; a MEMBERS constant
 *   lists each member in schema order with its JSON kind, whether it is
 *   required and nullable, and the wire class or enum it refers to. The
 *   strict decoder reads MEMBERS;
 * - one backed string enum per string enum of Go package core, cases in
 *   schema order (which is Go declaration order; the drift test checks it
 *   against go/core/enums.go);
 * - Wire.php: the TYPES and ENUMS tables, name => class.
 *
 * Every generated file carries the GENERATED line below; hand-written files
 * of src/Core/ never do. `php scripts/gen-types.php` writes the files;
 * `php scripts/gen-types.php --check` writes nothing and exits 1 when a
 * committed file differs from what the schema gives, or when a generated
 * file has no schema counterpart any more. Exit status 2: unusable schema.
 */

require \dirname(__DIR__) . '/vendor/autoload.php';

use HopTop\Pact\Core\JsonObject;
use HopTop\Pact\Vectors\Fixtures;

const GENERATED = '// Code generated by scripts/gen-types.php from schema/pact.schema.json. DO NOT EDIT.';

final class GenError extends \RuntimeException {}

/**
 * The schema walk and the PHP text of each generated file.
 *
 * @phpstan-type Row array{kind: string, items: ?string, required: bool, nullable: bool, ref: ?string, enum: ?string}
 */
final class GenTypes
{
    /** Inline object members with a class of their own, named as the Go structs. */
    private const INLINE = [
        'GatewayMetadata.endpoints' => 'GatewayEndpoints',
        'ReputationValue.dimensions' => 'ReputationDimensions',
    ];

    /** Payload schemas of extension values, not wire objects: no class (Go has none). */
    private const PAYLOAD_ONLY = ['ConformanceDeclaration', 'TransportDeclaration'];

    /** The string enums of Go package core with their Go documentation, in Go order. */
    private const ENUMS = [
        'RuleSource' => "Where a field rule's fact must come from.",
        'Comparison' => 'How a field rule compares the presented value.',
        'Mode' => 'The enforcement mode of a contract, attestation or gateway.',
        'EvidenceKind' => 'The kind of an evidence artifact.',
        'CheckStatus' => 'The result of one admission check.',
        'Decision' => 'The admission decision of an attestation.',
        'TerminalReason' => 'The terminal state recorded in an attestation.',
        'SecurityStatus' => 'The security standing of a reputation value.',
        'CausalAssessment' => 'Who caused an outcome.',
        'ReporterRole' => 'The role of the party that reports an outcome.',
        'EventKind' => 'The kind of an outcome event.',
        'OutcomeResult' => 'The result an outcome report states.',
        'Dimension' => 'The reputation dimension an outcome counts toward.',
        'Severity' => 'The severity of an outcome.',
        'BoundDirection' => 'Whether a metric bound is a lower or an upper limit.',
        'LearningMode' => 'The operating mode of a learning policy.',
        'ArtifactType' => 'The model type of a learning artifact.',
        'Transition' => 'The lifecycle transition a learning event requests.',
        'LifecycleState' => 'The state a learning artifact is expected to be in.',
        'AckStatus' => 'The status of an Acknowledgment.',
        'JWSAlgorithm' => 'A JWS algorithm a gateway accepts.',
        'PresentationTransport' => 'A way to carry a presentation to a gateway.',
    ];

    /** The enum of every schema member with an enum (directly or in its items): the Go field type. */
    private const ENUM_MEMBERS = [
        'FieldRule.source' => 'RuleSource',
        'FieldRule.comparison' => 'Comparison',
        'RequirementContract.mode' => 'Mode',
        'Evidence.kind' => 'EvidenceKind',
        'CheckResult.result' => 'CheckStatus',
        'AdmissionAttestation.decision' => 'Decision',
        'AdmissionAttestation.terminal_reason' => 'TerminalReason',
        'AdmissionAttestation.mode' => 'Mode',
        'ReputationValue.security_status' => 'SecurityStatus',
        'Attribution.causal_assessment' => 'CausalAssessment',
        'OutcomeReport.reporter_role' => 'ReporterRole',
        'OutcomeReport.event_kind' => 'EventKind',
        'OutcomeReport.result' => 'OutcomeResult',
        'OutcomeReport.dimension' => 'Dimension',
        'OutcomeReport.severity' => 'Severity',
        'MetricBound.direction' => 'BoundDirection',
        'LearningPolicy.mode' => 'LearningMode',
        'LearningPolicy.permitted_artifact_types' => 'ArtifactType',
        'LearningArtifact.model_type' => 'ArtifactType',
        'LearningEvent.transition' => 'Transition',
        'LearningEvent.expected_state' => 'LifecycleState',
        'Acknowledgment.status' => 'AckStatus',
        'GatewayMetadata.jws_algorithms' => 'JWSAlgorithm',
        'GatewayMetadata.modes' => 'Mode',
        'GatewayMetadata.presentation_transports' => 'PresentationTransport',
    ];

    /** @var array<string, array{doc: string, fields: list<array{name: string, row: Row, php: string, doc: ?string}>}> */
    private array $classes = [];

    /** @var array<string, list<string>> */
    private array $enumValues = [];

    /** @var array<string, true> */
    private array $used = [];

    public function __construct(private readonly JsonObject $defs) {}

    /**
     * The generated files: path relative to src/Core => PHP text.
     *
     * @return array<string, string>
     */
    public static function generate(string $schemaText): array
    {
        $schema = Fixtures::parseJson($schemaText);
        $defs = $schema instanceof JsonObject ? $schema->get('$defs') : null;
        if (!$defs instanceof JsonObject) {
            throw new GenError('the schema has no $defs object');
        }
        $g = new self($defs);
        foreach (self::PAYLOAD_ONLY as $name) {
            if (!$defs->has($name)) {
                throw new GenError(\sprintf('payload-only %s is not in the schema', $name));
            }
        }
        foreach ($defs as $name => $def) {
            if (!\in_array($name, self::PAYLOAD_ONLY, true)) {
                $g->build($name, \sprintf('The `%s` object of the schema (`$defs/%s`).', $name, $name), $def);
            }
        }
        foreach ([...array_keys(self::INLINE), ...array_keys(self::ENUM_MEMBERS)] as $key) {
            if (!isset($g->used[$key])) {
                throw new GenError(\sprintf('%s: named member is not in the schema', $key));
            }
        }
        $out = [];
        foreach ($g->classes as $name => $c) {
            $out[$name . '.php'] = self::renderClass($name, $c['doc'], $c['fields']);
        }
        foreach (self::ENUMS as $name => $doc) {
            $values = $g->enumValues[$name] ?? throw new GenError(\sprintf('enum %s is not used by the schema', $name));
            $out[$name . '.php'] = self::renderEnum($name, $doc, $values);
        }
        $out['Wire.php'] = self::renderWire(array_keys($g->classes), array_keys(self::ENUMS));

        return $out;
    }

    private function build(string $name, string $doc, mixed $def): void
    {
        if (isset($this->classes[$name])) {
            throw new GenError(\sprintf('class %s built twice', $name));
        }
        if (!$def instanceof JsonObject || $def->get('type') !== 'object' || $def->get('additionalProperties') !== false) {
            throw new GenError(\sprintf('%s: not a closed object', $name));
        }
        $props = $def->get('properties');
        if (!$props instanceof JsonObject) {
            throw new GenError(\sprintf('%s: no properties', $name));
        }
        $required = $def->get('required', []);
        if (!\is_array($required)) {
            throw new GenError(\sprintf('%s: required is not an array', $name));
        }
        foreach ($required as $r) {
            if (!\is_string($r) || !$props->has($r)) {
                throw new GenError(\sprintf('%s: required member %s has no property', $name, json_encode($r)));
            }
        }
        $this->classes[$name] = ['doc' => $doc, 'fields' => []];
        $fields = [];
        foreach ($props as $member => $p) {
            if (preg_match('/\A[a-z_][a-z0-9_]*\z/', $member) !== 1) {
                throw new GenError(\sprintf('%s.%s: not a PHP property name', $name, $member));
            }
            if (!$p instanceof JsonObject) {
                throw new GenError(\sprintf('%s.%s: not a schema object', $name, $member));
            }
            [$shape, $php, $doc] = $this->shape($name, $member, $p);
            $shape['required'] = \in_array($member, $required, true);
            $fields[] = ['name' => $member, 'row' => $shape, 'php' => $php, 'doc' => $doc];
        }
        $this->classes[$name]['fields'] = $fields;
    }

    /**
     * The MEMBERS row (required still false), the PHP type and the phpdoc type
     * of one member, or of the items or values of an array or map.
     *
     * @return array{Row, string, ?string}
     */
    private function shape(string $owner, string $member, JsonObject $p, bool $nested = false): array
    {
        $key = $owner . '.' . $member;
        $row = ['kind' => '', 'items' => null, 'required' => false, 'nullable' => false, 'ref' => null, 'enum' => null];
        // An anyOf beside a type only constrains values of that type (the
        // URI-or-token items of GatewayMetadata.extensions_supported).
        if ($p->has('anyOf') && !$p->has('type')) {
            $alts = $p->get('anyOf');
            if (\is_array($alts) && \count($alts) === 2 && $alts[0] instanceof JsonObject && $alts[1] instanceof JsonObject
                && $alts[1]->names() === ['type'] && $alts[1]->get('type') === 'null') {
                [$inner, $php, $doc] = $this->shape($owner, $member, $alts[0], $nested);
                if ($inner['nullable'] || $php === 'mixed') {
                    throw new GenError(\sprintf('%s: nested nullable', $key));
                }
                $inner['nullable'] = true;

                return [$inner, '?' . $php, $doc === null ? null : $doc . '|null'];
            }
            $kinds = [];
            foreach (\is_array($alts) ? $alts : [] as $a) {
                $kinds[] = $a instanceof JsonObject && $a->names() === ['type'] ? $a->get('type') : '?';
            }
            sort($kinds);
            if ($kinds !== ['boolean', 'object']) {
                throw new GenError(\sprintf('%s: unsupported anyOf', $key));
            }
            $row['kind'] = 'object|boolean';

            return [$row, 'mixed', null];
        }
        if ($p->has('$ref')) {
            $ref = $p->get('$ref');
            $name = \is_string($ref) && str_starts_with($ref, '#/$defs/') ? substr($ref, 8) : '';
            if (!$this->defs->has($name) || \in_array($name, self::PAYLOAD_ONLY, true)) {
                throw new GenError(\sprintf('%s: unusable $ref %s', $key, json_encode($ref)));
            }

            return [[...$row, 'kind' => 'object', 'ref' => $name], $name, null];
        }
        if ($p->has('enum')) {
            $enum = self::ENUM_MEMBERS[$key] ?? throw new GenError(\sprintf('%s: schema enum has no enum name', $key));
            $values = $p->get('enum');
            if (!\is_array($values) || $values === [] || array_filter($values, 'is_string') !== $values) {
                throw new GenError(\sprintf('%s: not a list of strings', $key));
            }
            /** @var list<string> $values */
            if (isset($this->enumValues[$enum]) && $this->enumValues[$enum] !== $values) {
                throw new GenError(\sprintf('%s: enum %s has two different value lists', $key, $enum));
            }
            $this->enumValues[$enum] = $values;
            $this->used[$key] = true;

            return [[...$row, 'kind' => 'string', 'enum' => $enum], 'string', null];
        }
        if ($p->has('const')) {
            $c = $p->get('const');
            if (\is_string($c)) {
                return [[...$row, 'kind' => 'string'], 'string', null];
            }
            if (\is_int($c)) {
                return [[...$row, 'kind' => 'integer'], 'int', null];
            }
            throw new GenError(\sprintf('%s: unsupported const', $key));
        }
        if (\count($p) === 0) {
            return [[...$row, 'kind' => 'any'], 'mixed', null];
        }
        $t = $p->get('type');
        $scalar = ['string' => 'string', 'integer' => 'int', 'number' => 'float', 'boolean' => 'bool'];
        if (\is_string($t) && isset($scalar[$t])) {
            return [[...$row, 'kind' => $t], $scalar[$t], null];
        }
        if ($t === 'array' || ($t === 'object' && $p->get('additionalProperties') instanceof JsonObject)) {
            if ($nested) {
                throw new GenError(\sprintf('%s: nested array or map', $key));
            }
            $sub = $t === 'array' ? $p->get('items', new JsonObject()) : $p->get('additionalProperties');
            if (!$sub instanceof JsonObject) {
                throw new GenError(\sprintf('%s: items are not a schema object', $key));
            }
            [$inner, $php] = $this->shape($owner, $member, $sub, true);
            if ($inner['nullable'] || $inner['kind'] === 'any' || $inner['kind'] === 'object|boolean'
                || ($inner['kind'] === 'object' && $inner['ref'] === null)) {
                throw new GenError(\sprintf('%s: unsupported items', $key));
            }
            $kind = $t === 'array' ? 'array' : 'object';
            $row = [...$row, 'kind' => $kind, 'items' => $inner['kind'], 'ref' => $inner['ref'], 'enum' => $inner['enum']];

            return $kind === 'array'
                ? [$row, 'array', 'list<' . $php . '>']
                : [$row, 'JsonObject', null];
        }
        if ($t === 'object') {
            if ($p->has('properties')) {
                $name = self::INLINE[$key] ?? throw new GenError(\sprintf('%s: inline object has no class name', $key));
                $this->used[$key] = true;
                $this->build($name, \sprintf('The `%s` member of %s.', $member, $owner), $p);

                return [[...$row, 'kind' => 'object', 'ref' => $name], $name, null];
            }

            return [[...$row, 'kind' => 'object'], 'JsonObject', null];
        }
        throw new GenError(\sprintf('%s: unsupported schema', $key));
    }

    /** @param list<array{name: string, row: Row, php: string, doc: ?string}> $fields */
    private static function renderClass(string $name, string $doc, array $fields): string
    {
        $rows = '';
        foreach ($fields as $f) {
            $r = $f['row'];
            $rows .= \sprintf(
                "        '%s' => ['kind' => '%s', 'items' => %s, 'required' => %s, 'nullable' => %s, 'ref' => %s, 'enum' => %s],\n",
                $f['name'],
                $r['kind'],
                $r['items'] === null ? 'null' : "'" . $r['items'] . "'",
                $r['required'] ? 'true' : 'false',
                $r['nullable'] ? 'true' : 'false',
                $r['ref'] === null ? 'null' : $r['ref'] . '::class',
                $r['enum'] === null ? 'null' : $r['enum'] . '::class',
            );
        }
        // Required members first: PHP refuses no optional parameter before a
        // required one without a deprecation. MEMBERS keeps the schema order.
        $ordered = [...array_filter($fields, static fn(array $f): bool => $f['row']['required']), ...array_filter($fields, static fn(array $f): bool => !$f['row']['required'])];
        $params = '';
        $docs = '';
        foreach ($ordered as $f) {
            $php = $f['php'];
            $opt = !$f['row']['required'];
            if ($opt && $php !== 'mixed' && !str_starts_with($php, '?')) {
                $php = '?' . $php;
            }
            $params .= \sprintf("        public %s $%s%s,\n", $php, $f['name'], $opt ? ' = null' : '');
            if ($f['doc'] !== null) {
                $docs .= \sprintf("     * @param %s $%s\n", $f['doc'] . ($opt ? '|null' : ''), $f['name']);
            }
        }
        $ctorDoc = $docs === '' ? '' : "    /**\n" . $docs . "     */\n";

        return self::head() . <<<PHP
            /**
             * {$doc}
             *
             * MEMBERS lists the JSON members in schema order: kind is the JSON type
             * (string, integer, number, boolean, object, array, object|boolean or
             * any), items the JSON type of the items of an array or the values of a
             * map, ref the wire class and enum the enum class of the member, its
             * items or its values. An enum member holds the string as received.
             */
            final readonly class {$name}
            {
                public const array MEMBERS = [
            {$rows}    ];

            {$ctorDoc}    public function __construct(
            {$params}    ) {}
            }

            PHP;
    }

    /** @param list<string> $values */
    private static function renderEnum(string $name, string $doc, array $values): string
    {
        $cases = '';
        $seen = [];
        foreach ($values as $v) {
            $case = strtoupper((string) preg_replace('/[^0-9A-Za-z]/', '_', $v));
            if (preg_match('/\A[A-Z_][A-Z0-9_]*\z/', $case) !== 1 || isset($seen[$case])) {
                throw new GenError(\sprintf('enum %s: value %s gives no distinct case name', $name, $v));
            }
            $seen[$case] = true;
            $cases .= \sprintf("    case %s = '%s';\n", $case, $v);
        }

        return self::head() . <<<PHP
            /** {$doc} */
            enum {$name}: string
            {
            {$cases}
                /** Whether \$s is a defined value. */
                public static function isValid(string \$s): bool
                {
                    return self::tryFrom(\$s) !== null;
                }
            }

            PHP;
    }

    /**
     * @param list<string> $classes
     * @param list<string> $enums
     */
    private static function renderWire(array $classes, array $enums): string
    {
        $t = implode('', array_map(static fn(string $n): string => \sprintf("        '%s' => %s::class,\n", $n, $n), $classes));
        $e = implode('', array_map(static fn(string $n): string => \sprintf("        '%s' => %s::class,\n", $n, $n), $enums));

        return self::head() . <<<PHP
            /** The generated wire classes and enums of this namespace, by name. */
            final class Wire
            {
                /** The wire classes: one per object definition of the schema, plus the inline objects. */
                public const array TYPES = [
            {$t}    ];

                /** The string enums, in Go declaration order. */
                public const array ENUMS = [
            {$e}    ];

                private function __construct() {}
            }

            PHP;
    }

    private static function head(): string
    {
        return "<?php\n\ndeclare(strict_types=1);\n\n" . GENERATED . "\n\nnamespace HopTop\\Pact\\Core;\n\n";
    }
}

/** @param list<string> $args */
function main(array $args): int
{
    $root = \dirname(__DIR__);
    $check = false;
    foreach ($args as $a) {
        if ($a !== '--check') {
            fwrite(\STDERR, "usage: php scripts/gen-types.php [--check]\n");

            return 2;
        }
        $check = true;
    }
    try {
        $text = @file_get_contents($root . '/schema/pact.schema.json');
        if ($text === false) {
            throw new GenError('schema/pact.schema.json cannot be read');
        }
        $out = GenTypes::generate($text);
    } catch (GenError|\UnexpectedValueException $e) {
        fwrite(\STDERR, 'gen-types: ' . $e->getMessage() . "\n");

        return 2;
    }
    $dir = $root . '/src/Core';
    $stale = [];
    foreach ($out as $file => $want) {
        $path = $dir . '/' . $file;
        $have = is_file($path) ? file_get_contents($path) : false;
        if ($have === $want) {
            continue;
        }
        if ($check) {
            $stale[] = $file;
        } elseif (file_put_contents($path, $want) === false) {
            fwrite(\STDERR, \sprintf("gen-types: cannot write src/Core/%s\n", $file));

            return 2;
        }
    }
    foreach (glob($dir . '/*.php') ?: [] as $path) {
        $file = basename($path);
        $text = file_get_contents($path);
        if (!isset($out[$file]) && \is_string($text) && str_contains($text, GENERATED)) {
            if ($check) {
                $stale[] = $file;
            } else {
                unlink($path);
            }
        }
    }
    foreach ($stale as $file) {
        fwrite(\STDERR, \sprintf("gen-types: src/Core/%s is stale; run php scripts/gen-types.php\n", $file));
    }

    return $stale === [] ? 0 : 1;
}

$argv = $_SERVER['argv'] ?? [];
exit(main(\is_array($argv) ? array_values(array_filter(\array_slice($argv, 1), 'is_string')) : []));
