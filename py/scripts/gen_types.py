"""Generate hop_top_pact.core.types and hop_top_pact.core.enums.

Inputs, both read from the source repository:

- the vendored schema ``src/hop_top_pact/schema/pact.schema.json``: one
  frozen dataclass per ``$defs`` entry, plus one per inline object member
  (``GatewayEndpoints``, ``ReputationDimensions``, named as in Go), each with
  a ``_MEMBERS`` table of its JSON members;
- the Go enum table ``go/core/enums.go``: one ``StrEnum`` per Go string
  type, members in Go declaration order, named after their values.

A member whose ``enum`` has the value set of exactly one generated enum is
typed with that enum. Standard library only. ``--check`` compares instead of
writing and exits 1 when a committed file is stale.

Usage: python scripts/gen_types.py [--check] [--schema PATH] [--go-enums PATH]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

PY_ROOT = Path(__file__).resolve().parents[1]
SCHEMA = PY_ROOT / "src" / "hop_top_pact" / "schema" / "pact.schema.json"
GO_ENUMS = PY_ROOT.parent / "go" / "core" / "enums.go"
TYPES_OUT = PY_ROOT / "src" / "hop_top_pact" / "core" / "types.py"
ENUMS_OUT = PY_ROOT / "src" / "hop_top_pact" / "core" / "enums.py"

# Inline object members get a class of their own, named as the Go struct.
INLINE_NAMES = {
    ("GatewayMetadata", "endpoints"): "GatewayEndpoints",
    ("ReputationValue", "dimensions"): "ReputationDimensions",
}

# The line length of ruff.toml: the output is ruff-format clean as written.
LINE_LENGTH = 100

HEADER = '"""{doc}\n\nGenerated by scripts/gen_types.py from {source}. Do not edit.\n"""\n'


class GenError(Exception):
    pass


@dataclass(frozen=True)
class Enum:
    name: str
    doc: str
    values: tuple[str, ...]


def parse_go_enums(text: str) -> list[Enum]:
    """Read every ``type X string`` and the constants of type X, in order."""
    enums: list[Enum] = []
    lines = text.splitlines()
    type_re = re.compile(r"^type (\w+) string$")
    const_re = re.compile(r'^\s+\w+\s+(\w+)\s+=\s+"([^"]*)"$')
    values: dict[str, list[str]] = {}
    docs: dict[str, str] = {}
    order: list[str] = []
    for i, line in enumerate(lines):
        m = type_re.match(line)
        if m:
            name = m.group(1)
            order.append(name)
            values[name] = []
            doc: list[str] = []
            j = i - 1
            while j >= 0 and lines[j].startswith("//"):
                doc.insert(0, lines[j][2:].strip())
                j -= 1
            docs[name] = " ".join(doc)
            continue
        m = const_re.match(line)
        if m and m.group(1) in values:
            values[m.group(1)].append(m.group(2))
    for name in order:
        if not values[name]:
            raise GenError(f"go enum {name} has no constants")
        enums.append(Enum(name, docs[name], tuple(values[name])))
    if not enums:
        raise GenError("no go enum types found")
    return enums


def member_name(value: str) -> str:
    name = re.sub(r"[^0-9A-Za-z]", "_", value).upper()
    if not name.isidentifier():
        raise GenError(f"enum value {value!r} gives no identifier")
    return name


def render_enums(enums: list[Enum], source: str) -> str:
    out = [HEADER.format(doc="String enums of the PACT wire format.", source=source)]
    out.append("from __future__ import annotations\n\nfrom enum import StrEnum\n")
    exported = sorted(e.name for e in enums)
    out.append("__all__ = [\n" + "".join(f'    "{n}",\n' for n in exported) + "]\n")
    for e in enums:
        out.append(f"\nclass {e.name}(StrEnum):")
        out.append(f'    """{e.doc}"""\n' if e.doc else "")
        names = [member_name(v) for v in e.values]
        if len(set(names)) != len(names):
            raise GenError(f"enum {e.name}: member names collide")
        for n, v in zip(names, e.values, strict=True):
            out.append(f'    {n} = "{v}"')
        out.append("")
        out.append("    @classmethod")
        out.append("    def is_valid(cls, s: str) -> bool:")
        out.append('        """Report whether s is a defined value."""')
        out.append("        return s in cls._value2member_map_\n")
    return "\n".join(out).rstrip("\n") + "\n"


@dataclass(frozen=True)
class Field:
    name: str
    annotation: str
    kind: str
    required: bool
    nullable: bool
    ref: str | None


# The payload-only definitions of the schema: payload schemas of extension
# values, not wire objects, with no class of their own (Go package core has
# no struct for them either).
PAYLOAD_ONLY = ("ConformanceDeclaration", "TransportDeclaration")


class TypeBuilder:
    def __init__(self, schema: dict[str, Any], enums: list[Enum]) -> None:
        self.defs: dict[str, Any] = schema["$defs"]
        self.by_values: dict[frozenset[str], list[str]] = {}
        for e in enums:
            self.by_values.setdefault(frozenset(e.values), []).append(e.name)
        self.classes: dict[str, list[Field]] = {}
        self.docs: dict[str, str] = {}
        self.used_enums: set[str] = set()

    def enum_for(self, values: list[Any], where: str) -> str:
        if not all(isinstance(v, str) for v in values):
            raise GenError(f"{where}: non-string enum")
        names = self.by_values.get(frozenset(values), [])
        if len(names) != 1:
            raise GenError(f"{where}: enum {values} matches {len(names)} go enums")
        self.used_enums.add(names[0])
        return names[0]

    def annotate(
        self, owner: str, member: str, p: dict[str, Any]
    ) -> tuple[str, str, bool, str | None]:
        """Return (annotation, json kind, nullable, referenced class)."""
        where = f"{owner}.{member}"
        # An anyOf beside a type only constrains values of that type (the
        # URI-or-token items of GatewayMetadata.extensions_supported).
        if "anyOf" in p and "type" not in p:
            alts = p["anyOf"]
            non_null = [a for a in alts if a.get("type") != "null"]
            if len(non_null) == len(alts) - 1 and len(non_null) == 1:
                ann, kind, _, ref = self.annotate(owner, member, non_null[0])
                return ann, kind, True, ref
            kinds = sorted(a.get("type", "?") for a in alts)
            if kinds == ["boolean", "object"] and all(set(a) == {"type"} for a in alts):
                return "JSONObject | bool", "object|boolean", False, None
            raise GenError(f"{where}: unsupported anyOf {alts}")
        if "$ref" in p:
            ref = p["$ref"].removeprefix("#/$defs/")
            if ref not in self.defs:
                raise GenError(f"{where}: unknown $ref {p['$ref']}")
            return ref, "object", False, ref
        if "const" in p:
            c = p["const"]
            if isinstance(c, str):
                return "str", "string", False, None
            if isinstance(c, int) and not isinstance(c, bool):
                return "int", "integer", False, None
            raise GenError(f"{where}: unsupported const {c!r}")
        if "enum" in p:
            return self.enum_for(p["enum"], where), "string", False, None
        if p == {}:
            return "JSONValue", "any", False, None
        t = p.get("type")
        if t == "string":
            return "str", "string", False, None
        if t == "integer":
            return "int", "integer", False, None
        if t == "number":
            return "float", "number", False, None
        if t == "boolean":
            return "bool", "boolean", False, None
        if t == "array":
            item, _, nullable, ref = self.annotate(owner, member, p.get("items", {}))
            if nullable:
                raise GenError(f"{where}: nullable array items")
            return f"tuple[{item}, ...]", "array", False, ref
        if t == "object":
            if "properties" in p:
                name = INLINE_NAMES.get((owner, member))
                if name is None:
                    raise GenError(f"{where}: inline object without a class name")
                self.build(name, p, f"The {member!r} object of {owner}.")
                return name, "object", False, name
            extra = p.get("additionalProperties")
            if isinstance(extra, dict):
                value, _, nullable, ref = self.annotate(owner, member, extra)
                if nullable:
                    raise GenError(f"{where}: nullable map values")
                return f"Mapping[str, {value}]", "object", False, ref
            return "JSONObject", "object", False, None
        raise GenError(f"{where}: unsupported schema {p}")

    def build(self, name: str, d: dict[str, Any], doc: str) -> None:
        if name in self.classes:
            raise GenError(f"class {name} built twice")
        if d.get("type") != "object" or d.get("additionalProperties") is not False:
            raise GenError(f"{name}: not a closed object")
        self.classes[name] = []
        self.docs[name] = doc
        required = set(d.get("required", []))
        unknown = required - set(d["properties"])
        if unknown:
            raise GenError(f"{name}: required members without a property: {sorted(unknown)}")
        fields = []
        for member, p in d["properties"].items():
            if not member.isidentifier():
                raise GenError(f"{name}.{member}: not an identifier")
            ann, kind, nullable, ref = self.annotate(name, member, p)
            fields.append(Field(member, ann, kind, member in required, nullable, ref))
        self.classes[name] = fields


def render_types(b: TypeBuilder, source: str) -> str:
    names = list(b.classes)
    enums = sorted(b.used_enums)
    out = [HEADER.format(doc="Wire types of the PACT protocol.", source=source)]
    out.append("from __future__ import annotations\n")
    out.append("from collections.abc import Mapping")
    out.append("from dataclasses import dataclass")
    out.append("from types import MappingProxyType")
    out.append("from typing import ClassVar, Final, TypeAlias\n")
    out.append("from hop_top_pact.core.enums import (")
    out.extend(f"    {e}," for e in enums)
    out.append(")\n")
    # isort-style, as ruff's RUF022 wants: constants first, then the rest.
    all_names = sorted(
        ["JSONObject", "JSONValue", "Member", "TYPES", *names],
        key=lambda n: (not n.isupper(), n),
    )
    out.append("__all__ = [\n" + "".join(f'    "{n}",\n' for n in all_names) + "]\n")
    out.append(
        "JSONValue: TypeAlias = (\n"
        '    "Mapping[str, JSONValue] | tuple[JSONValue, ...] | str | int | float | bool | None"\n'
        ")\n"
        "JSONObject: TypeAlias = Mapping[str, JSONValue]\n"
    )
    out.append(
        "\n@dataclass(frozen=True, slots=True)\n"
        "class Member:\n"
        '    """One JSON member of a wire type.\n\n'
        "    kind is the JSON type: string, integer, number, boolean, object, array,\n"
        "    object|boolean or any. ref names the wire type of an object member, an\n"
        '    array item or a map value, when it has one.\n    """\n\n'
        "    name: str\n    kind: str\n    required: bool\n    nullable: bool\n"
        "    ref: str | None"
    )
    for name in names:
        fields = b.classes[name]
        out.append("\n\n@dataclass(frozen=True, slots=True, kw_only=True)")
        out.append(f"class {name}:")
        out.append(f'    """{b.docs[name]}"""\n')
        for f in fields:
            ann = f.annotation + (" | None" if f.nullable or not f.required else "")
            default = "" if f.required else " = None"
            out.append(f"    {f.name}: {ann}{default}")
        out.append("")
        out.append("    _MEMBERS: ClassVar[Mapping[str, Member]] = MappingProxyType(")
        out.append("        {")
        for f in fields:
            ref = f'"{f.ref}"' if f.ref else "None"
            args = f'"{f.name}", "{f.kind}", {f.required}, {f.nullable}, {ref}'
            line = f'            "{f.name}": Member({args}),'
            if len(line) <= LINE_LENGTH:
                out.append(line)
            else:
                out.append(f'            "{f.name}": Member(')
                out.append(f"                {args}")
                out.append("            ),")
        out.append("        }")
        out.append("    )")
    out.append("\n")
    out.append("TYPES: Final[Mapping[str, type]] = MappingProxyType(")
    out.append("    {")
    out.extend(f'        "{n}": {n},' for n in names)
    out.append("    }")
    out.append(")")
    return "\n".join(out).rstrip("\n") + "\n"


def generate(schema_path: Path, go_enums_path: Path) -> dict[Path, str]:
    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    enums = parse_go_enums(go_enums_path.read_text(encoding="utf-8"))
    b = TypeBuilder(schema, enums)
    for name in PAYLOAD_ONLY:
        if name not in schema["$defs"]:
            raise GenError(f"payload-only {name} is not in the schema")
    for name, d in schema["$defs"].items():
        if name in PAYLOAD_ONLY:
            continue
        b.build(name, d, d.get("description") or f"The {name} wire type (schema $defs).")
    return {
        ENUMS_OUT: render_enums(enums, "go/core/enums.go"),
        TYPES_OUT: render_types(b, "the vendored schema"),
    }


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when a generated file is stale")
    ap.add_argument("--schema", type=Path, default=SCHEMA)
    ap.add_argument("--go-enums", type=Path, default=GO_ENUMS)
    args = ap.parse_args(argv)
    try:
        outputs = generate(args.schema, args.go_enums)
    except (GenError, OSError, ValueError, KeyError) as e:
        print(f"gen_types: {e}", file=sys.stderr)
        return 2
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path)
        else:
            path.write_text(text, encoding="utf-8")
    for path in stale:
        print(
            f"gen_types: {path.relative_to(PY_ROOT)} is stale; run python scripts/gen_types.py",
            file=sys.stderr,
        )
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
