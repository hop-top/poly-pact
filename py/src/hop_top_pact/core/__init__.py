"""Wire types and enums of the PACT protocol. Mirrors hop.top/pact-go/core.

``types`` and ``enums`` are generated by ``scripts/gen_types.py`` from the
vendored schema and the Go enum table; do not edit them by hand. The limits
of draft section 20.1 (``core.limits``) are re-exported here, as the Go
package holds them; the time rules are in ``core.clock``.
"""

from typing import Final

from hop_top_pact.core.enums import *  # noqa: F403
from hop_top_pact.core.enums import __all__ as _enums_all
from hop_top_pact.core.limits import *  # noqa: F403
from hop_top_pact.core.limits import __all__ as _limits_all
from hop_top_pact.core.types import *  # noqa: F403
from hop_top_pact.core.types import __all__ as _types_all

VERSION: Final = "0.1"
"""The protocol version every artifact carries in pact_version."""

DIGEST_LEN: Final = 43
"""The length of a base64url SHA-256 value without padding."""


class Digest(str):
    """A base64url (RFC 4648, no padding) SHA-256 value, such as an object digest
    or a JWK thumbprint. The schema pattern is ``^[A-Za-z0-9_-]{43}$``.
    """

    __slots__ = ()

    def validate(self) -> None:
        """Raise ValueError unless the digest is exactly 43 base64url characters."""
        if len(self) != DIGEST_LEN:
            raise ValueError(f"core: digest has {len(self)} characters, want {DIGEST_LEN}")
        for i, c in enumerate(self):
            if c not in _BASE64URL:
                raise ValueError(f"core: digest has invalid character {c!r} at offset {i}")


_BASE64URL: Final = frozenset("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_")


__all__ = ["DIGEST_LEN", "VERSION", "Digest", *_enums_all, *_limits_all, *_types_all]
